"""Generate C# packet helpers from the existing C++ protocol definitions.

Run from any directory: python -I path/to/generate_csharp.py
Use --check to verify that the checked-in output is current.
"""

import argparse
from pathlib import Path
import re


COMMON = Path(__file__).resolve().parent
DEFAULT_OUTPUT = COMMON.parents[1] / "CSharpDummy/CSharpDummy/Protocol/PacketGenerated.cs"
SCALARS = {"int": "int", "char": "sbyte", "uint8": "byte",
           "AccountNo": "long", "ObjectID": "int", "ItemID": "int"}
FIXED_STRINGS = {"ID": 12, "Password": 12, "Nickname": 20}
ENUMS = {"ServerType": "byte", "eLoginResult": "byte",
         "eRegisterResult": "byte", "eObjectType": "ushort"}


CS_KEYWORDS = set("""abstract as base bool break byte case catch char checked class const
continue decimal default delegate do double else enum event explicit extern false finally
fixed float for foreach goto if implicit in int interface internal is lock long namespace
new null object operator out override params private protected public readonly ref return
sbyte sealed short sizeof stackalloc static string struct switch this throw true try typeof
uint ulong unchecked unsafe ushort using virtual void volatile while""".split())


def identifier(name):
    return "@" + name if name in CS_KEYWORDS else name


def is_received(name):
    # The dummy is a client, so it only decodes and handles server responses.
    return name.split("_", 1)[1].startswith("Res")


def parse_packets(text):
    text = re.sub(r"//[^\n]*", "", text)
    packets = []
    names = set()
    pattern = re.compile(r"\s*(\w+)\s*:\s*\{([^{}]*)\}")
    position = 0
    while text[position:].strip():
        match = pattern.match(text, position)
        if not match:
            raise ValueError(f"Invalid packet definition near {text[position:position + 80]!r}")
        name, body = match.groups()
        if name in names:
            raise ValueError(f"Duplicate packet: {name}")
        names.add(name)
        fields = []
        for field in body.split(","):
            if not field.strip():
                continue
            field_match = re.fullmatch(r"\s*((?:psh::)?\w+)\s*:\s*(\w+)\s*", field)
            if not field_match:
                raise ValueError(f"Invalid field in {name}: {field!r}")
            cpp_type, field_name = field_match.groups()
            fields.append((cpp_type.removeprefix("psh::"), field_name))
        packets.append((name, fields))
        position = match.end()
    return packets


def cs_type(kind):
    if kind in SCALARS:
        return SCALARS[kind]
    if kind in FIXED_STRINGS or kind == "String":
        return "string"
    if kind == "SessionKey":
        return "byte[]"
    if kind in ENUMS or kind in ("FVector", "bool"):
        return kind
    raise ValueError(f"Unsupported protocol type: {kind}")


def write_field(kind, name):
    if kind in FIXED_STRINGS:
        return [f"packet.WriteFixedString({name}, {FIXED_STRINGS[kind]});"]
    if kind == "String":
        return [f"packet.WriteString({name});"]
    if kind == "SessionKey":
        return [f"if ({name}.Length != 64)",
                f'    throw new ArgumentException("SessionKey must contain 64 bytes.", nameof({name}));',
                f"packet.WriteBytes({name});"]
    if kind == "FVector":
        return [f"packet.Write({name}.X);", f"packet.Write({name}.Y);"]
    if kind == "bool":
        return [f"packet.Write((byte)({name} ? 1 : 0));"]
    if kind in ENUMS:
        return [f"packet.Write(({ENUMS[kind]}){name});"]
    return [f"packet.Write({name});"]


def read_field(kind, name):
    if kind in FIXED_STRINGS:
        return [f"{name} = reader.ReadFixedString({FIXED_STRINGS[kind]});"]
    if kind == "String":
        return [f"{name} = reader.ReadString();"]
    if kind == "SessionKey":
        return [f"{name} = new byte[64];", f"reader.ReadBytes({name});"]
    if kind == "FVector":
        return [f"{name} = new FVector(reader.Read<float>(), reader.Read<float>());"]
    if kind == "bool":
        return [f"{name} = reader.Read<byte>() != 0;"]
    if kind in ENUMS:
        return [f"{name} = ({kind})reader.Read<{ENUMS[kind]}>();"]
    return [f"{name} = reader.Read<{cs_type(kind)}>();"]


def generate():
    packets = parse_packets((COMMON / "PacketDefine.txt").read_text(encoding="utf-8-sig"))
    types = (COMMON / "ContentTypes.h").read_text(encoding="utf-8-sig")
    lines = ["// <auto-generated />", "// 원본: src/Common/PacketDefine.txt, ContentTypes.h",
             "using System;", "using System.IO;", "using CSharpDummy.NetLib;", "", "namespace CSharpDummy;", "",
             "public enum PacketType : ushort", "{"]
    for number, (name, _) in enumerate(packets):
        lines.append(f"    {name} = {number},")
    lines += [f"    None = {len(packets)},", "}", ""]
    for name, base in ENUMS.items():
        match = re.search(rf"enum class {name}\s*:\s*(\w+)\s*\{{([^}}]*)\}}", types)
        expected = {"byte": "uint8", "ushort": "uint16"}[base]
        if not match or match[1] != expected:
            raise ValueError(f"Missing or changed enum layout: {name}")
        lines += [f"public enum {name} : {base}", "{"]
        body = re.sub(r"//[^\n]*", "", match[2])
        for member in body.split(","):
            if member.strip():
                lines.append(f"    {member.strip()},")
        lines += ["}", ""]
    lines += ["public readonly record struct FVector(float X, float Y);", ""]
    for name, fields in packets:
        args = ", ".join(f"{cs_type(kind)} {field[0].upper() + field[1:]}" for kind, field in fields)
        lines += [f"public sealed record {name}({args});", ""]
    received = [name for name, _ in packets if is_received(name)]
    lines += ["// Protocol.Deserialize에서만 만들기 때문에 Body는 항상 Type과 일치한다.",
              "public readonly record struct ReceivedPacket(PacketType Type, object Body);", "",
              "public interface IPacketHandler", "{"]
    lines += [f"    void On{name}({name} packet);" for name in received]
    lines += ["}", ""]
    lines += ["// Make는 패킷 타입을 SendPacket.Type에 넣는다. Get은 패킷 타입을 이미 읽은 상태를 가정한다.",
              "// 헤더, 체크섬, 암호화는 전송 계층에서 따로 처리한다.",
              "public static class Protocol", "{"]
    for name, fields in packets:
        args = "".join(f", {cs_type(kind)} {identifier(field)}" for kind, field in fields)
        lines += [f"    public static void Make{name}(SendPacket packet{args})", "    {",
                  f"        packet.Type = PacketType.{name};"]
        for kind, field in fields:
            lines += ["        " + line for line in write_field(kind, identifier(field))]
        lines += ["    }", ""]
        lines += [f"    public static {name} Get{name}(ref PacketReader reader)", "    {"]
        for kind, field in fields:
            statements = read_field(kind, identifier(field))
            statements[0] = f"{cs_type(kind)} " + statements[0]
            lines += ["        " + line for line in statements]
        args = ", ".join(identifier(field) for _, field in fields)
        lines += [f"        return new {name}({args});", "    }", ""]
    lines += ["    // 패킷 타입을 이미 읽은 상태를 가정한다.",
              "    public static ReceivedPacket Deserialize(PacketType type, ref PacketReader reader)", "    {",
              "        switch (type)", "        {"]
    lines += [f"            case PacketType.{name}: return new ReceivedPacket(type, Get{name}(ref reader));"
              for name in received]
    lines += ["            default: throw new InvalidDataException($\"Unexpected packet type: {type}\");",
              "        }", "    }", ""]
    lines += ["    public static void Dispatch(ReceivedPacket packet, IPacketHandler handler)", "    {",
              "        switch (packet.Type)", "        {"]
    lines += [f"            case PacketType.{name}: handler.On{name}(({name})packet.Body); break;"
              for name in received]
    lines += ["            default: throw new InvalidDataException($\"Unexpected packet type: {packet.Type}\");",
              "        }", "    }", "}", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = generate()
    if args.check:
        if not args.output.exists() or args.output.read_text(encoding="utf-8") != output:
            parser.exit(1, f"Generated file is outdated: {args.output}\n")
        print("C# protocol output is up to date.")
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(output, encoding="utf-8", newline="\n")
        print(f"Generated {args.output}")


if __name__ == "__main__":
    main()
